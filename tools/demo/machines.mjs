// Runs demo.kstar with the real `kstar` and turns the three tables it prints
// (the eps-NFA, the DFA and the minimal DFA) into machines.js, which the
// animation reads. Nothing in the animation is typed in by hand except where
// each state is placed on screen.
//
//   node machines.mjs            uses the debug build: cargo run from the repo root
//   KSTAR=path/to/kstar node machines.mjs

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");

export function runKstar() {
  const program = join(here, "demo.kstar");
  const [cmd, args] = process.env.KSTAR
    ? [process.env.KSTAR, ["run", program]]
    : ["cargo", ["run", "--quiet", "--bin", "kstar", "--", "run", program]];
  return execFileSync(cmd, args, { cwd: root, encoding: "utf8" });
}

// One printed machine: a header line, a column header, then one row per state:
//   "-> *{q0,q1,q2} | {q3,q4} | {}"
function parseTable(lines) {
  const header = lines[0].trim();
  const symbols = lines[1].split("|").slice(1).map((s) => s.trim());
  const states = [];
  let start = null;
  const accept = [];
  const edges = []; // { from, to, label }
  for (const row of lines.slice(2)) {
    const cells = row.split("|");
    let name = cells[0].trim();
    const isStart = name.startsWith("->");
    if (isStart) name = name.slice(2).trim();
    if (name.startsWith("*")) { name = name.slice(1); accept.push(name); }
    if (isStart) start = name;
    states.push(name);
    cells.slice(1).forEach((cell, i) => {
      const value = cell.trim();
      if (value === "-") return;
      // NFA cells are sets "{q1, q2}"; DFA cells are single states, which may
      // themselves be named after sets ("{q3,q4}", "{}").
      const targets = /, /.test(value) || header.startsWith("eps-NFA")
        ? value.replace(/^\{|\}$/g, "").split(", ").filter(Boolean)
        : [value];
      for (const to of targets) {
        const label = symbols[i] === "eps" ? "ε" : symbols[i];
        const same = edges.find((e) => e.from === name && e.to === to);
        if (same) same.label += ", " + label; else edges.push({ from: name, to, label });
      }
    });
  }
  return { header, states, start, accept, edges };
}

export function parseMachines(output) {
  const lines = output.split(/\r?\n/);
  const machines = [];
  let current = null;
  for (const line of lines) {
    if (/^(eps-NFA|NFA|DFA) with \d+ states/.test(line)) {
      current = [line];
      machines.push(current);
    } else if (current && line.includes("|")) {
      current.push(line);
    } else {
      current = null;
    }
  }
  if (machines.length !== 3) throw new Error(`expected 3 machines in the output, found ${machines.length}:\n${output}`);
  const [nfa, dfa, min] = machines.map(parseTable);
  const tests = lines.find((l) => l.startsWith("tests:"));
  if (!tests || !/ 0 failed/.test(tests)) throw new Error(`demo.kstar's tests did not all pass:\n${output}`);
  return { nfa, dfa, min };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const machines = parseMachines(runKstar());
  writeFileSync(join(here, "machines.js"),
    "// Generated by machines.mjs from the output of demo.kstar. Do not edit.\n" +
    `window.MACHINES = ${JSON.stringify(machines, null, 2)};\n`);
  console.log("wrote tools/demo/machines.js:", machines.nfa.header, "/", machines.dfa.header, "/", machines.min.header);
}
