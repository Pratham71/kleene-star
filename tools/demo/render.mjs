// Captures demo.html into assets/demo.gif and assets/demo.png.
//
//   npm run build                  machines.js from kstar, then the GIF and the still
//   node render.mjs --stills DIR   also writes every fifth frame (200 ms apart) into DIR, to check frames
//
// It drives a browser that is already installed (Chrome or Edge; set
// BROWSER=path to choose one) through puppeteer-core, so nothing is
// downloaded. The animation is a pure function of time, so each frame is
// rendered by setting the clock, not by waiting.

import { mkdirSync, writeFileSync, existsSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import puppeteer from "puppeteer-core";
import { PNG } from "pngjs";
import gifenc from "gifenc";
import { parseMachines, runKstar } from "./machines.mjs";

const { GIFEncoder, quantize, applyPalette } = gifenc;
const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, "..", "..", "assets");
const WIDTH = 960, HEIGHT = 440, FPS = 25;

function findBrowser() {
  const candidates = [
    process.env.BROWSER,
    // Chrome first: Edge's startup boost can make a headless Edge exit at once.
    "C:/Program Files/Google/Chrome/Application/chrome.exe",
    "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
    "C:/Program Files/Microsoft/Edge/Application/msedge.exe",
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
    "/usr/bin/google-chrome", "/usr/bin/chromium", "/usr/bin/chromium-browser", "/usr/bin/microsoft-edge",
  ].filter(Boolean);
  const found = candidates.find((p) => existsSync(p));
  if (!found) throw new Error("no Edge or Chrome found; set BROWSER to the path of one");
  return found;
}

// 1. The machines, from the real kstar.
const machines = parseMachines(runKstar());
writeFileSync(join(here, "machines.js"),
  "// Generated by machines.mjs from the output of demo.kstar. Do not edit.\n" +
  `window.MACHINES = ${JSON.stringify(machines, null, 2)};\n`);
console.log(`kstar: ${machines.nfa.header} / ${machines.dfa.header} / ${machines.min.header}`);

// 2. The frames.
const stillsAt = process.argv.indexOf("--stills");
const stillsDir = stillsAt > 0 ? process.argv[stillsAt + 1] : null;
if (stillsDir) mkdirSync(stillsDir, { recursive: true });

const browser = await puppeteer.launch({ executablePath: findBrowser(), headless: true, args: ["--force-color-profile=srgb", "--font-render-hinting=none"] });
const page = await browser.newPage();
await page.setViewport({ width: WIDTH, height: HEIGHT, deviceScaleFactor: 1 });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(pathToFileURL(join(here, "demo.html")).href);
await page.evaluate(() => window.READY);
if (errors.length) throw new Error("the page failed: " + errors.join("; "));
const total = await page.evaluate(() => window.DEMO_TOTAL);
const still = await page.evaluate(() => window.DEMO_STILL);

async function frameAt(t) {
  await page.evaluate((t) => window.render(t), t);
  const png = PNG.sync.read(Buffer.from(await page.screenshot({ type: "png", clip: { x: 0, y: 0, width: WIDTH, height: HEIGHT } })));
  return png;
}

const step = 1000 / FPS;
const frames = [];
for (let i = 0; i * step < total; i++) {
  const t = i * step;
  const png = await frameAt(t);
  frames.push(png.data);
  if (stillsDir && i % 5 === 0) writeFileSync(join(stillsDir, `t${String(Math.round(t)).padStart(5, "0")}.png`), PNG.sync.write(png));
}
const last = await frameAt(still);
writeFileSync(join(assets, "demo.png"), PNG.sync.write(last));
await browser.close();
if (errors.length) throw new Error("the page failed: " + errors.join("; "));

// 3. The GIF: one palette for every frame (no flicker), identical frames
// merged into one longer frame, and only the pixels that changed written
// (the rest is transparent and shows the frame before).
// Sample pixels from every frame, so colours that appear briefly are kept.
const all = new Uint8Array(frames.length * 4096 * 4);
frames.forEach((f, i) => { for (let k = 0; k < 4096; k++) { const o = ((k * 7919) % (WIDTH * HEIGHT)) * 4; all.set(f.subarray(o, o + 4), (i * 4096 + k) * 4); } });
const palette = quantize(all, 255, { format: "rgb565" });
const TRANSPARENT = palette.length; // one spare index for "unchanged"
palette.push([255, 0, 255]);

const gif = GIFEncoder();
let previous = null;
let pending = null; // { index, delay, diff }
let first = true;
const flush = () => {
  if (!pending) return;
  gif.writeFrame(pending.index, WIDTH, HEIGHT, {
    palette: first ? palette : undefined,
    delay: pending.delay,
    repeat: 0,
    transparent: pending.diff,
    transparentIndex: TRANSPARENT,
    dispose: 1,
  });
  first = false;
  pending = null;
};
for (const data of frames) {
  const index = applyPalette(data, palette, "rgb565");
  if (previous) {
    let changed = false;
    const diff = new Uint8Array(index.length);
    for (let k = 0; k < index.length; k++) {
      if (index[k] === previous[k]) diff[k] = TRANSPARENT; else { diff[k] = index[k]; changed = true; }
    }
    if (!changed) { pending.delay += step; continue; }
    flush();
    pending = { index: diff, delay: step, diff: true };
  } else {
    pending = { index, delay: step, diff: false };
  }
  previous = index;
}
flush();
gif.finish();
writeFileSync(join(assets, "demo.gif"), gif.bytes());

const size = statSync(join(assets, "demo.gif")).size;
console.log(`wrote assets/demo.gif: ${WIDTH}x${HEIGHT}, ${frames.length} frames at ${FPS} fps, ${(total / 1000).toFixed(1)} s, ${(size / 1024 / 1024).toFixed(2)} MB`);
console.log(`wrote assets/demo.png: the frame at ${still} ms`);
